void printLog(LogLevel level, const string& message) {
    string color;
    string prefix;

    switch (level) {
        case LogLevel::Info:
            color = COLOR_INFO;
            prefix = "[INFO]";
            break;
        case LogLevel::Warn:
            color = COLOR_WARN;
            prefix = "[WARN]";
            break;
        case LogLevel::Error:
            color = COLOR_ERROR;
            prefix = "[ERROR]";
            break;
    }

    cout << color << prefix << COLOR_RESET << " " << message << endl;
}